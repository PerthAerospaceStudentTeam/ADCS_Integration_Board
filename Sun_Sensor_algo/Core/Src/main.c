int map(int x, int in_min, int in_max, int out_min, int out_max) {
    if (x < in_min) {
        x = in_min;
    }
    if (x > in_max) {
        x = out_max;
    }
    return (int)((int32_t)(x - in_min) * (out_max - out_min) / (in_max - in_min) + out_min);
}

uint16_t top_vals[3];
uint8_t  top_idx[3];
float    top_lamb[3];

void top3(const uint16_t*data, uint16_t*out_vals, uint8_t*out_idx)
{
    for (uint8_t i = 0; i < 3; i++) {
        out_vals[i] = 0;
        out_idx[i]  = 0xFF;
    }

    for (uint8_t i = 0; i < 6; i++) {
        if (data[i] > out_vals[0]) {
            out_vals[2] = out_vals[1]; out_idx[2] = out_idx[1];
            out_vals[1] = out_vals[0]; out_idx[1] = out_idx[0];
            out_vals[0] = data[i];     out_idx[0] = i;
        } else if (data[i] > out_vals[1]) {
            out_vals[2] = out_vals[1]; out_idx[2] = out_idx[1];
            out_vals[1] = data[i];     out_idx[1] = i;
        } else if (data[i] > out_vals[2]) {
            out_vals[2] = data[i];     out_idx[2] = i;
        }
    }
}

float getAngle(float intensity) {
    float val = 1940.0f / (intensity + 940.0f);
    return 88.0f * powf(val - 1.0f, 1.0f / 3.3f);
}

float getLambertian(uint16_t adc, uint16_t minVal, uint16_t maxVal) {
    float value = (float)map(adc, minVal, maxVal, 0, 1000);
    float angle = getAngle(value);
    return cosf(angle * (float)M_PI / 180.0f); // cos expects radians
}


